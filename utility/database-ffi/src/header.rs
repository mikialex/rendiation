use crate::*;

pub struct CppHeaderOptions {
  pub namespace: String,
  /// headers that declare the `rdb_*` entry points, the entity handle type and the status type
  pub includes: Vec<String>,
  pub entity_handle_type: String,
  pub status_type: String,
  /// the opaque type that owns the heap parts of the read value
  pub snapshot_type: String,
}

impl FfiSchema {
  pub fn generate_cpp_header(&self, options: &CppHeaderOptions) -> String {
    let mut types = String::new();
    let mut emitted = FastHashSet::default();
    for c in &self.components {
      emit_type_definitions(&c.value, options, &mut emitted, &mut types);
    }

    let mut out = String::new();
    out
      .push_str("// Generated by database-ffi from the registered database schema, do not edit.\n");
    out.push_str("#pragma once\n\n#include <cstddef>\n#include <cstdint>\n");
    for include in &options.includes {
      writeln!(out, "#include \"{include}\"").unwrap();
    }
    let ns = &options.namespace;
    let handle = &options.entity_handle_type;
    writeln!(out, "\nnamespace {ns} {{\n").unwrap();
    writeln!(
      out,
      "constexpr uint64_t SCHEMA_HASH = {:#018x}ull;\n",
      self.hash
    )
    .unwrap();
    writeln!(
      out,
      "template <typename E> struct Handle {{\n  {handle} raw;\n}};\n"
    )
    .unwrap();
    out.push_str("template <typename T> struct Optional {\n  bool has_value;\n  T value;\n};\n\n");
    out.push_str("/// utf8 string, the read value is always nul terminated\n");
    out.push_str("struct Str {\n  const char *ptr;\n  size_t len;\n};\n\n");
    out.push_str("template <typename T> struct Slice {\n  const T *ptr;\n  size_t len;\n};\n\n");
    let snapshot = &options.snapshot_type;
    writeln!(
      out,
      "/// keeps the heap parts (Str, Slice) of the read value alive
class Snapshot {{
public:
  Snapshot() = default;
  Snapshot(const Snapshot &) = delete;
  Snapshot &operator=(const Snapshot &) = delete;
  Snapshot(Snapshot &&other) noexcept : owner(other.owner) {{ other.owner = nullptr; }}
  Snapshot &operator=(Snapshot &&other) noexcept {{
    reset();
    owner = other.owner;
    other.owner = nullptr;
    return *this;
  }}
  ~Snapshot() {{ reset(); }}
  void reset() {{
    rdb_snapshot_drop(owner);
    owner = nullptr;
  }}
  {snapshot} **reset_and_get() {{
    reset();
    return &owner;
  }}

private:
  {snapshot} *owner = nullptr;
}};
"
    )
    .unwrap();

    out.push_str("namespace entity {\n");
    for e in &self.entities {
      writeln!(out, "/// {}", e.name).unwrap();
      writeln!(
        out,
        "struct {} {{\n  static constexpr uint64_t key = {:#018x}ull;\n}};",
        e.c_name, e.key
      )
      .unwrap();
    }
    out.push_str("} // namespace entity\n\n");

    out.push_str("namespace types {\n");
    out.push_str(&types);
    out.push_str("} // namespace types\n\n");

    out.push_str("namespace component {\n");
    for c in &self.components {
      let entity = &self.entity_by_id(c.entity).unwrap().c_name;
      let value = self.component_value_type(c, options);
      writeln!(out, "/// {}", c.name).unwrap();
      writeln!(out, "struct {} {{", c.c_name).unwrap();
      writeln!(out, "  using Entity = entity::{entity};").unwrap();
      writeln!(out, "  using Value = {value};").unwrap();
      writeln!(out, "  static constexpr uint64_t key = {:#018x}ull;", c.key).unwrap();
      writeln!(
        out,
        "  static constexpr bool has_heap_data = {};",
        c.has_heap_data
      )
      .unwrap();
      out.push_str("};\n");
      let value_name = format!("{}::Value", c.c_name);
      emit_size_assert(&mut out, &value_name, c.value.size(), c.value.align());
    }
    out.push_str("} // namespace component\n\n");

    let status = &options.status_type;
    out.push_str("inline bool check_schema() { return rdb_schema_hash() == SCHEMA_HASH; }\n\n");
    writeln!(
      out,
      "template <typename E> inline Handle<E> create() {{\n  return Handle<E>{{rdb_entity_create(E::key)}};\n}}\n"
    )
    .unwrap();
    writeln!(
      out,
      "template <typename E> inline {status} destroy(Handle<E> handle) {{\n  return rdb_entity_drop(E::key, handle.raw);\n}}\n"
    )
    .unwrap();
    writeln!(
      out,
      "template <typename C>\ninline {status} write(Handle<typename C::Entity> handle, const typename C::Value &value) {{\n  return rdb_component_write(C::key, handle.raw, &value);\n}}\n"
    )
    .unwrap();
    writeln!(
      out,
      "template <typename C>
inline {status} read(Handle<typename C::Entity> handle, typename C::Value &out) {{
  static_assert(!C::has_heap_data, \"the value contains heap data, read it with a Snapshot\");
  return rdb_component_read(C::key, handle.raw, &out, nullptr);
}}

/// the heap parts of out are valid until the snapshot is reset or dropped
template <typename C>
inline {status} read(Handle<typename C::Entity> handle, typename C::Value &out, Snapshot &snapshot) {{
  return rdb_component_read(C::key, handle.raw, &out, snapshot.reset_and_get());
}}
"
    )
    .unwrap();

    if !self.unsupported.is_empty() {
      out.push_str("// components not exposed yet:\n");
      for c in &self.unsupported {
        writeln!(out, "//   {}: {}", c.name, c.reason).unwrap();
      }
      out.push('\n');
    }

    writeln!(out, "}} // namespace {ns}").unwrap();
    out
  }

  fn component_value_type(&self, c: &FfiComponent, options: &CppHeaderOptions) -> String {
    if let Some(target) = c.foreign_key
      && let CType::Optional(inner) = &c.value
      && matches!(inner.as_ref(), CType::EntityHandle)
      && let Some(target) = self.entity_by_id(target)
    {
      return format!("Optional<Handle<entity::{}>>", target.c_name);
    }
    declare(&c.value, "", options)
  }
}

/// C declarator syntax, the array dimension goes after the name.
fn declare(ty: &CType, name: &str, options: &CppHeaderOptions) -> String {
  match ty.c_visible() {
    CType::Array { element, count } => declare(element, &format!("{name}[{count}]"), options),
    other => {
      let ty = type_ref(other, options);
      if name.is_empty() {
        ty
      } else {
        format!("{ty} {name}")
      }
    }
  }
}

fn type_ref(ty: &CType, options: &CppHeaderOptions) -> String {
  match ty.c_visible() {
    CType::Primitive { kind, .. } => kind.c_name().to_string(),
    CType::EntityHandle => options.entity_handle_type.clone(),
    CType::Struct(s) => format!("types::{}", s.c_name),
    CType::Enum(e) => format!("types::{}", e.c_name),
    CType::Optional(inner) => format!("Optional<{}>", declare(inner, "", options)),
    CType::Array { .. } => declare(ty, "", options),
    CType::Str => "Str".into(),
    CType::Slice { element, .. } => format!("Slice<{}>", declare(element, "", options)),
    _ => unreachable!(),
  }
}

/// post order, so that every type is defined before used
fn emit_type_definitions(
  ty: &CType,
  options: &CppHeaderOptions,
  emitted: &mut FastHashSet<String>,
  out: &mut String,
) {
  match ty.c_visible() {
    CType::Array { element, .. } => emit_type_definitions(element, options, emitted, out),
    CType::Optional(inner) => emit_type_definitions(inner, options, emitted, out),
    CType::Slice { element, .. } => emit_type_definitions(element, options, emitted, out),
    CType::Struct(s) => emit_struct(s, options, emitted, out),
    CType::Enum(e) => {
      if !emitted.insert(e.c_name.clone()) {
        return;
      }
      for v in &e.variants {
        if let Some(payload) = &v.payload {
          emit_struct(payload, options, emitted, out);
        }
      }
      emit_enum(e, out);
    }
    _ => {}
  }
}

fn emit_struct(
  s: &CStruct,
  options: &CppHeaderOptions,
  emitted: &mut FastHashSet<String>,
  out: &mut String,
) {
  if !emitted.insert(s.c_name.clone()) {
    return;
  }
  for f in &s.fields {
    emit_type_definitions(&f.ty, options, emitted, out);
  }
  writeln!(out, "struct {} {{", s.c_name).unwrap();
  for f in &s.fields {
    writeln!(out, "  {};", declare(&f.ty, &f.c_name, options)).unwrap();
  }
  out.push_str("};\n");
  emit_size_assert(out, &s.c_name, s.size, s.align);
  for f in &s.fields {
    writeln!(
      out,
      "static_assert(offsetof({}, {}) == {}, \"layout mismatch\");",
      s.c_name, f.c_name, f.offset
    )
    .unwrap();
  }
  out.push('\n');
}

fn emit_enum(e: &CEnum, out: &mut String) {
  let tags = |indent: &str| {
    let mut tags = String::new();
    for v in &e.variants {
      writeln!(tags, "{indent}{} = {},", v.c_name, v.tag).unwrap();
    }
    tags
  };

  if !e.has_payload() {
    writeln!(
      out,
      "enum class {} : uint32_t {{\n{}}};\n",
      e.c_name,
      tags("  ")
    )
    .unwrap();
    return;
  }

  writeln!(out, "struct {} {{", e.c_name).unwrap();
  writeln!(out, "  enum class Tag : uint32_t {{\n{}  }};", tags("    ")).unwrap();
  out.push_str("  Tag tag;\n  union {\n");
  for v in &e.variants {
    if let Some(payload) = &v.payload {
      writeln!(out, "    {} {};", payload.c_name, v.c_name).unwrap();
    }
  }
  out.push_str("  } payload;\n};\n");
  emit_size_assert(out, &e.c_name, e.size, e.align);
  writeln!(
    out,
    "static_assert(offsetof({}, payload) == {}, \"layout mismatch\");\n",
    e.c_name, e.payload_offset
  )
  .unwrap();
}

fn emit_size_assert(out: &mut String, name: &str, size: usize, align: usize) {
  writeln!(
    out,
    "static_assert(sizeof({name}) == {size} && alignof({name}) == {align}, \"layout mismatch\");"
  )
  .unwrap();
}
